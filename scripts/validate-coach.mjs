import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import assert from 'node:assert/strict';
const model = readFileSync(new URL('../public/coach/model.glb', import.meta.url));
const manifest = JSON.parse(readFileSync(new URL('../public/coach/model-manifest.json', import.meta.url)));
assert.equal(manifest.schemaVersion, '1.0.0');
assert.equal(model.subarray(0, 4).toString(), 'glTF');
assert.equal(model.readUInt32LE(4), 2);
assert.equal(model.readUInt32LE(8), model.length);
assert.equal(manifest.integrity.modelBytes, model.length);
assert.equal(createHash('sha256').update(model).digest('hex'), manifest.integrity.modelChecksum);
assert.equal(manifest.integrity.algorithm, 'SHA-256');
assert.ok(['cm', 'm', 'in'].includes(manifest.dimensions.units));
for (const field of ['width', 'height', 'depth']) assert.ok(manifest.dimensions[field] > 0);
for (const field of ['position', 'target']) assert.ok(manifest.camera[field].length === 3 && manifest.camera[field].every(Number.isFinite));
const gltf = JSON.parse(model.subarray(20, 20 + model.readUInt32LE(12)).toString());
assert.ok(gltf.meshes.length > 0);
for (const item of [...(gltf.buffers || []), ...(gltf.images || [])]) assert.equal(item.uri, undefined, 'Model must embed all required assets');
const preview = readFileSync(new URL('../public/coach/preview.png', import.meta.url));
assert.equal(preview.subarray(0, 8).toString('hex'), '89504e470d0a1a0a');
console.log(`Confirmed ${manifest.modelName}, version ${manifest.handoffVersion}: ${gltf.meshes.length} meshes, ${gltf.animations?.length || 0} animation, checksum matches, all assets embedded.`);
